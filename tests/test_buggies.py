"""Pruebas del Tour de Buggies. Uso: python3 -I test_buggies.py <URL_BASE> <carpeta>"""
import sys, urllib.parse
from playwright.sync_api import sync_playwright
BASE = sys.argv[1].rstrip("/") + "/tours/"; OUT = sys.argv[2]; DATE = "2026-10-23"
res = []
def check(n, c, d=""):
    res.append(bool(c)); print(("PASA " if c else "FALLA") + " | " + n + (" | " + d if d else ""))
with sync_playwright() as p:
    br = p.chromium.launch()
    ctx = br.new_context(**p.devices["iPhone 13"], timezone_id="America/Santo_Domingo", locale="es-DO")
    pg = ctx.new_page(); pg.add_init_script("window.__JGT_CAPTURE__=function(u){window.__lastUrl=u;};")
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(BASE, wait_until="load")
    check("Al abrir, se ve el selector y ningún tour abierto", pg.locator(".chooser").is_visible() and not pg.locator("#buggiesTour").is_visible() and not pg.locator("#cityTour").is_visible())
    pg.click('.choice[data-tour="buggies"]'); pg.wait_for_timeout(300)
    check("Al tocar «Buggies» se abre Buggies y no el City Tour", pg.locator("#buggiesTour").is_visible() and not pg.locator("#cityTour").is_visible())
    price = lambda: pg.locator("#bQuotePrice").inner_text().strip()
    check("Título de la landing", "Buggies y Four Wheel en Comatillo" in pg.locator("#buggiesTour").inner_text())
    check("Incluye 4 elementos", pg.locator("#buggiesTour .incl li").count() == 4)
    check("Galería con 8 fotos propias", pg.locator("#buggiesTour .s-gallery img[src^='img/b-']").count() == 8)
    check("Se llama «Tour de Buggies y Four Wheel» en el selector", "Tour de Buggies y Four Wheel" in pg.locator('.choice[data-tour="buggies"]').inner_text())
    check("Sin personas elegidas no hay precio", price() == "—")
    for n, exp in [("1", "US$153"), ("2", "US$226"), ("3", "US$298"), ("4", "US$371"), ("16+", "A cotizar")]:
        pg.select_option("#bPeople", n); check(f"{n} persona(s) = {exp}", price() == exp, price())
    pg.select_option("#bPeople", "2")
    check("Con 2 personas sugiere 1 vehículo", pg.input_value("#bCount") == "1")
    check("Horario mañana indica recogida 7:30 a.m.", "7:30 a.m." in pg.locator('#bShift option[value="manana"]').inner_text())
    check("Horario tarde indica recogida 12:30 p.m.", "12:30 p.m." in pg.locator('#bShift option[value="tarde"]').inner_text())
    check("Opciones de vehículo: four wheel, buggy y ambos", pg.locator("#bVehicle option").count() == 3)
    pg.select_option("#bCount", "2")
    check("2 personas en 2 vehículos = US$226 (precio por persona)", price() == "US$226", price())
    check("Detalle muestra «2 four wheels»", "2 four wheels" in pg.locator("#bQuoteNote").inner_text())
    pg.select_option("#bVehicle", "buggy")
    check("Detalle muestra «2 buggies»", "2 buggies" in pg.locator("#bQuoteNote").inner_text())
    pg.select_option("#bVehicle", "four"); pg.select_option("#bCount", "1"); pg.select_option("#bFood", "si")
    check("2 personas + comida = US$238", price() == "US$238", price())
    pg.select_option("#bFood", "no"); pg.select_option("#bPlan", "plus")
    check("Plus, 2 personas = US$242", price() == "US$242", price())
    check("Selector del formulario marca la tarjeta Plus", pg.is_checked('input[name="bPlanPick"][value="plus"]'))
    pg.select_option("#bPlan", "basico")
    check("Ya no menciona santuario ni tabaco", "Santuario" not in pg.locator("#buggiesTour").inner_text() and "tabaco" not in pg.locator("#buggiesTour").inner_text())
    check("Nota muestra reserva del 30 % y resto al abordar", "Reserva con US$68 (30 %) y paga US$158 al abordar" in pg.locator("#bQuoteNote").inner_text(), pg.locator("#bQuoteNote").inner_text())
    check("Barra inferior muestra el total", "US$226" in pg.locator("#bBarPrice").inner_text())
    check("Muestra precio por persona en grupo", "US$113 por persona" in pg.locator("#bQuoteNote").inner_text())
    pg.select_option("#bPickupZone", "otra"); check("Otra zona = A cotizar", price() == "A cotizar"); pg.select_option("#bPickupZone", "boca")
    pg.click("#bSubmitBtn"); pg.wait_for_timeout(300)
    check("Formulario incompleto no abre la ventana", not pg.locator("#bConfirmBox").is_visible())
    pg.fill("#bDate", "2026-10-01"); pg.fill("#bPickup", "Hotel Don Juan"); pg.fill("#bName", "Cliente de Prueba"); pg.fill("#bPhone", "+1 809 555 1234")
    pg.click("#bSubmitBtn"); pg.wait_for_timeout(300)
    check("Fecha pasada bloqueada", not pg.locator("#bConfirmBox").is_visible())
    pg.click('label.plan:has(input[value="plus"])'); pg.select_option("#bShift", "tarde"); pg.select_option("#bVehicle", "buggy")
    pg.select_option("#bCount", "3"); pg.fill("#bDate", DATE); pg.click("#bSubmitBtn"); pg.wait_for_timeout(300)
    check("Bloquea más vehículos que personas", not pg.locator("#bConfirmBox").is_visible() and "más vehículos" in pg.locator('.err[data-for="bCount"]').inner_text())
    pg.select_option("#bPeople", "4"); pg.select_option("#bCount", "1"); pg.click("#bSubmitBtn"); pg.wait_for_timeout(300)
    check("Bloquea 4 personas en 1 vehículo", not pg.locator("#bConfirmBox").is_visible() and "al menos 2" in pg.locator('.err[data-for="bCount"]').inner_text())
    pg.select_option("#bPeople", "2"); pg.select_option("#bCount", "1")
    pg.fill("#bDate", DATE); pg.click("#bSubmitBtn"); pg.wait_for_timeout(300)
    check("Ventana muestra US$242 (Plus, 2 personas) antes de WhatsApp", pg.locator("#bConfirmBox").is_visible() and pg.locator("#bCPrice").inner_text() == "US$242")
    check("Ventana muestra reserva US$73 y resto US$169", "US$73" in pg.locator("#bCDeposit").inner_text() and "US$169" in pg.locator("#bCDeposit").inner_text() and pg.locator("#bCDeposit").is_visible())
    check("Ventana de buggies no dice «sin pagos anticipados»", "Sin pagos anticipados" not in pg.locator("#bConfirmBox").inner_text())
    pg.screenshot(path=f"{OUT}/buggies-ventana.png")
    pg.click("#bWaLink"); pg.wait_for_timeout(600)
    u = pg.evaluate("window.__lastUrl") or ""; msg = urllib.parse.unquote(u.split("?text=", 1)[-1])
    check("Enlace a wa.me/18298182426", u.startswith("https://wa.me/18298182426?text="))
    for f in ["Nombre: Cliente de Prueba", "WhatsApp: +1 809 555 1234", "Excursión: Buggies y Four Wheel en Comatillo", "Plan: Tour Plus (2 ríos + Salto Alto + La Orqueta)", "Vehículo: Buggy", "Cantidad de vehículos: 1", "Comida: No, gracias", "Horario: Tarde · te recogemos 12:30 p.m. (ruta 2:00 – 5:00)", "Recogida: Hotel Don Juan (Boca Chica)", "Fecha: 23/10/2026", "Personas: 2", "Precio estimado: US$242", "Reserva (30 %): US$73", "Resto al abordar: US$169"]:
        check(f"Mensaje contiene «{f}»", f in msg)
    check("Sin desbordes horizontales", not pg.evaluate("document.documentElement.scrollWidth > window.innerWidth"))
    check("Sin errores de JavaScript", not errs, "; ".join(errs))
    pg.goto(BASE + "#buggies", wait_until="load"); pg.wait_for_timeout(300)
    check("Enlace directo /tours/#buggies abre Buggies", pg.locator("#buggiesTour").is_visible())
    pg.goto(BASE, wait_until="load"); pg.wait_for_timeout(300)
    pg.screenshot(path=f"{OUT}/hub2.png")
    br.close()
print(f"\nRESULTADO: {sum(res)}/{len(res)} pruebas superadas"); sys.exit(0 if all(res) else 1)
